/**
 * Generates supabase/seed.sql from the fictional demo catalogue so the database seed
 * can never drift from the data the demo mode shows.
 *
 *   npm run db:seed:generate
 */
import { writeFileSync } from "node:fs";
import { DEMO_OPPORTUNITIES } from "../src/data/demo-opportunities.ts";

const text = (value: string | null | undefined) =>
  value === null || value === undefined ? "null" : `'${value.replaceAll("'", "''")}'`;
const num = (value: number | undefined) => (value === undefined ? "null" : String(value));
const arr = (values: string[]) =>
  values.length ? `array[${values.map(text).join(", ")}]::text[]` : "'{}'::text[]";

const lines: string[] = [
  "-- GENERATED by scripts/generate-supabase-seed.ts. Do not edit by hand.",
  "-- Every record is fictional demonstration data (is_demo = true, unverified, no links).",
  "begin;",
  "delete from opportunities where is_demo;",
];

for (const o of DEMO_OPPORTUNITIES) {
  const c = o.compensation;
  lines.push(
    `insert into opportunities (slug, title, provider_name, provider_url, category, summary, description, benefits,
  compensation_type, compensation_min, compensation_max, compensation_currency, compensation_period, compensation_note,
  location_mode, locations, deadline, is_rolling, start_date, duration, skills, tags, application_url, source_url,
  status, verification_status, last_verified_at, published_at, is_demo)
values (${text(o.slug)}, ${text(o.title)}, ${text(o.providerName)}, null, '${o.category}', ${text(o.summary)}, ${text(o.description)}, ${arr(o.benefits)},
  '${c.type}', ${num(c.amountMin)}, ${num(c.amountMax)}, ${text(c.currency)}, ${text(c.period)}, ${text(c.note)},
  '${o.locationMode}', ${arr(o.locations)}, ${text(o.deadline)}, ${o.isRolling}, ${text(o.startDate)}, ${text(o.duration)}, ${arr(o.skills)}, ${arr(o.tags)}, null, null,
  'published', 'unverified', null, ${text(o.publishedAt)}, true);`,
  );
  o.requirements.forEach((requirement, position) => {
    const { kind, mandatory, statedText, ...rest } = requirement;
    const params: Record<string, unknown> = { ...rest };
    delete params.id;
    lines.push(
      `insert into opportunity_requirements (opportunity_id, position, kind, mandatory, stated_text, params)
select id, ${position}, '${kind}', ${mandatory}, ${text(statedText)}, ${text(JSON.stringify(params))}::jsonb from opportunities where slug = ${text(o.slug)};`,
    );
  });
}

lines.push("commit;", "");

const target = new URL("../supabase/seed.sql", import.meta.url);
writeFileSync(target, lines.join("\n"));
console.log(`Wrote ${DEMO_OPPORTUNITIES.length} demo opportunities to supabase/seed.sql`);
